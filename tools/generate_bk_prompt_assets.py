#!/usr/bin/env python3
"""Generate BK read-only PCM from the shared 8 kHz prompt and ringtone WAVs."""
import argparse
import struct
import wave
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'platforms/beken/runtime/assets/xiaotai_prompt_assets.h'


def generate():
    lines = ['/* Generated by tools/generate_bk_prompt_assets.py; do not edit. */',
             '#ifndef XIAOTAI_PROMPT_ASSETS_H', '#define XIAOTAI_PROMPT_ASSETS_H',
             '#include <stdint.h>']
    assets = [(f'xiaotai_ack_{v}', f'prompts/ai_ack_{v}_8k.wav') for v in ('female', 'male')]
    assets += [(f'xiaotai_ring_{k}', f'rings/kids_watch_{k}_tiny.wav') for k in ('incoming', 'outgoing')]
    for symbol, filename in assets:
        path = ROOT / 'product/assets/audio' / filename
        with wave.open(str(path), 'rb') as wav:
            if (wav.getframerate(), wav.getnchannels(), wav.getsampwidth()) != (8000, 1, 2):
                raise ValueError(f'Invalid PCM format: {path.name}')
            samples = struct.unpack('<' + 'h' * wav.getnframes(), wav.readframes(wav.getnframes()))
        lines.append(f'static const int16_t {symbol}[] = {{')
        lines.extend('    ' + ', '.join(map(str, samples[i:i+16])) + ','
                     for i in range(0, len(samples), 16))
        lines.append('};')
    lines.extend(['#endif', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('BK prompt assets are stale')
    else:
        OUTPUT.write_text(text)
