#!/usr/bin/env python3
"""Generate BK read-only PCM from the shared 8 kHz acknowledgement WAVs."""
import argparse
import struct
import wave
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'firmware/beken/bk7258/lckfb-bk7258-xiaotai/ap/assets/xiaotai_prompt_assets.h'


def generate():
    lines = ['/* Generated by tools/generate_bk_prompt_assets.py; do not edit. */',
             '#ifndef XIAOTAI_PROMPT_ASSETS_H', '#define XIAOTAI_PROMPT_ASSETS_H',
             '#include <stdint.h>']
    for voice in ('female', 'male'):
        path = ROOT / f'product/assets/audio/prompts/ai_ack_{voice}_8k.wav'
        with wave.open(str(path), 'rb') as wav:
            if (wav.getframerate(), wav.getnchannels(), wav.getsampwidth()) != (8000, 1, 2):
                raise ValueError(f'Invalid PCM format: {path.name}')
            samples = struct.unpack('<' + 'h' * wav.getnframes(), wav.readframes(wav.getnframes()))
        lines.append(f'static const int16_t xiaotai_ack_{voice}[] = {{')
        lines.extend('    ' + ', '.join(map(str, samples[i:i+16])) + ','
                     for i in range(0, len(samples), 16))
        lines.append('};')
    lines.extend(['#endif', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('BK prompt assets are stale')
    else:
        OUTPUT.write_text(text)
